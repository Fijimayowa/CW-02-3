import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:cloud_functions/cloud_functions.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';

import 'app.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`

// Run with --dart-define=USE_EMULATORS=false to talk to the real Firebase project.
const bool useEmulators =
    bool.fromEnvironment('USE_EMULATORS', defaultValue: true);

// On a physical phone, set this to your computer's LAN IP with
// --dart-define=EMULATOR_HOST=192.168.x.x
const String emulatorHostOverride = String.fromEnvironment('EMULATOR_HOST');

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  if (kDebugMode && useEmulators) {
    final isAndroid = !kIsWeb && defaultTargetPlatform == TargetPlatform.android;
    // Android emulator reaches your computer at 10.0.2.2; iOS simulator uses localhost.
    final host = emulatorHostOverride.isNotEmpty
        ? emulatorHostOverride
        : (isAndroid ? '10.0.2.2' : 'localhost');
    await FirebaseAuth.instance.useAuthEmulator(host, 9099);
    FirebaseFirestore.instance.useFirestoreEmulator(host, 8080);
    FirebaseFunctions.instance.useFunctionsEmulator(host, 5001);
  }

  runApp(const CloudQuestApp())
}
